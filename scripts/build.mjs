// story.json -> timing.json + index.html (root timeline) + compositions/captions.html
// Scenes are hand-made sub-compositions in compositions/scene-<name>.html.
// A scene that does not exist yet renders as compositions/_placeholder.html (animatic).
//
//   node scripts/build.mjs episodes/<slug>
import fs from 'node:fs';
import path from 'node:path';
import { episodeDir, loadStory, esc, marks, plain, round } from './lib.mjs';

const dir = episodeDir(process.argv[2]);
const S = loadStory(dir);
const comp = f => path.join(dir, 'compositions', f);

// ---- 1. timing.json (read by voice.mjs and score.mjs, and by you when animating scenes)
// consecutive shots on the same scene share one sub-composition clip
const groups = [];
for (const s of S.shots) {
  const g = groups[groups.length - 1];
  if (g && g.scene === s.scene) { g.shots.push(s); g.dur = round(g.dur + s.dur); }
  else groups.push({ scene: s.scene, start: s.start, dur: s.dur, shots: [s] });
}
groups.forEach((g, k) => {
  g.id = `${g.scene}-${k}`;
  g.file = fs.existsSync(comp(`scene-${g.scene}.html`)) ? `scene-${g.scene}.html` : '_placeholder.html';
  g.compId = g.file === '_placeholder.html' ? 'placeholder' : `scene-${g.scene}`;
  // shot times local to the scene clip — what you animate against inside the scene file
  g.local = g.shots.map(s => ({ shot: s.i, at: round(s.start - g.start), dur: s.dur, text: plain(s.text) }));
});
fs.writeFileSync(path.join(dir, 'timing.json'), JSON.stringify({
  title: S.title, bpm: S.bpm, beat: round(S.beat), total: S.total, totalBeats: S.totalBeats,
  shots: S.shots.map(({ i, scene, start, dur, beats, text, style }) => ({ i, scene, start, dur, beats, text, style })),
  scenes: groups.map(({ id, scene, file, start, dur, local }) => ({ id, scene, file, start, dur, local })),
}, null, 1));

// ---- 2. captions sub-composition (one timed clip per shot, slide-up through a mask)
// captionLook: "bold" (default, big Kanit) or "folk" (smaller line on a dark pill, for slow folklore tales)
const look = S.captionLook === 'folk' ? ' folk' : '';
// format "landscape": subtitles sit in the bottom band of the 16:9 frame (kit.css .land)
const land = S.format === 'landscape' ? ' land' : '';
const caps = S.shots.filter(s => s.text).map(s => {
  const lines = s.text.split('\n').map(l => `<span class="cap-line"><span data-layout-allow-overflow>${marks(l)}</span></span>`).join('');
  return `      <div id="cap-${s.i}" class="clip cap${look}${land} ${s.style === 'red' ? 'red' : ''}" data-start="${s.start}" data-duration="${s.dur}" data-track-index="1">${lines}</div>`;
}).join('\n');
const capTweens = S.shots.filter(s => s.text).map(s => {
  const n = s.text.split('\n').length;
  let t = '';
  for (let k = 0; k < n; k++) {
    const sel = `#cap-${s.i} .cap-line:nth-child(${k + 1}) > span`;
    const at = round(s.start + k * 0.08);
    t += `        tl.fromTo("${sel}", { yPercent: 105 }, { yPercent: 0, duration: 0.26, ease: "power3.out" }, ${at});\n`;
    if (s.style === 'red') t += `        tl.fromTo("${sel}", { scaleX: 0.6 }, { scaleX: 1, duration: 0.3, ease: "back.out(2.2)" }, ${at});\n`;
  }
  return t;
}).join('');
fs.writeFileSync(comp('captions.html'), `<!doctype html>
<!-- GENERATED by scripts/build.mjs from story.json — edit story.json, not this file. -->
<html>
  <head><meta charset="UTF-8" /></head>
  <body>
    <template>
      <link rel="stylesheet" href="assets/kit/kit.css" />
      <style>
        #root { position: absolute; inset: 0; pointer-events: none; }
      </style>
      <div id="root" data-composition-id="captions" data-width="${S.W}" data-height="${S.H}">
      <div class="vignette"></div>
      <div class="cap-band${land}"></div>
${caps}
      </div>
      <script>
        const tl = gsap.timeline({ paused: true });
${capTweens}        window.__timelines["captions"] = tl;
      </script>
    </template>
  </body>
</html>
`);

// ---- 3. root index.html
// the cast must live in the document: external <use href="file.svg#id"> does not render
// story kits (assets/kit/stories/*.svg, ids prefixed per story) go into the same sprite
const castFile = path.join(dir, 'assets', 'kit', 'cast.svg');
const storyDir = path.join(dir, 'assets', 'kit', 'stories');
const storyFiles = fs.existsSync(storyDir) ? fs.readdirSync(storyDir).filter(f => f.endsWith('.svg')).sort().map(f => path.join(storyDir, f)) : [];
const spriteBody = (file) => fs.readFileSync(file, 'utf8').replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
const castSprite = fs.existsSync(castFile)
  ? ('<svg width="0" height="0" style="position:absolute" aria-hidden="true">' + [castFile, ...storyFiles].map(spriteBody).join('') + '</svg>').replace(/\s*\n\s*/g, ' ').trim()
  : '';
// a scene that declares a "shots" variable gets its shots as JSON per instance — local start, length, `view`, `who`
// and, once voiced, the local window of the line ([from, to]) — so it animates against the real timing (which
// moves whenever voice lengths change) instead of hard-coded seconds
const takesShots = g => g.file !== '_placeholder.html' && /"id"\s*:\s*"shots"/.test(fs.readFileSync(comp(g.file), 'utf8'));
const voIndex = path.join(dir, 'assets', 'vo', 'index.json');
const voLines = new Map(fs.existsSync(voIndex) ? JSON.parse(fs.readFileSync(voIndex, 'utf8')).map(v => [v.shot, v]) : []);
const shotsVar = g => JSON.stringify(g.shots.map((s, k) => {
  const v = voLines.get(s.i);
  return { at: g.local[k].at, dur: s.dur, view: s.view || '', who: s.who || '', vo: v ? [round(v.start - g.start), round(v.start - g.start + v.dur)] : null };
}));
const varAttr = v => ` data-variable-values='${JSON.stringify(v).replace(/'/g, '&#39;')}'`;
const hosts = groups.map(g => {
  const vars = g.file === '_placeholder.html'
    ? varAttr({ label: g.scene, note: g.shots.map(s => plain(s.text).replace(/\n/g, ' ')).join(' / ') })
    : takesShots(g) ? varAttr({ shots: shotsVar(g) }) : '';
  return `      <div id="${g.id}" data-composition-id="${g.compId}" data-composition-src="compositions/${g.file}"${vars}
        data-start="${g.start}" data-duration="${g.dur}" data-track-index="0" data-width="${S.W}" data-height="${S.H}"></div>`;
}).join('\n');
const audio = [];
if (fs.existsSync(path.join(dir, 'assets', 'score.wav')))
  audio.push(`      <audio id="score" src="assets/score.wav" data-start="0" data-duration="${S.total}" data-track-index="3" data-volume="1"></audio>`);
if (fs.existsSync(path.join(dir, 'assets', 'voice.wav')))
  audio.push(`      <audio id="voice" src="assets/voice.wav" data-start="0" data-duration="${S.total}" data-track-index="4" data-volume="1"></audio>`);

fs.writeFileSync(path.join(dir, 'index.html'), `<!doctype html>
<!-- GENERATED by scripts/build.mjs from story.json — edit story.json, not this file. -->
<html lang="th" data-resolution="${S.format}">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${S.W}, height=${S.H}" />
    <title>${esc(S.title || 'episode')}</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { margin: 0; width: ${S.W}px; height: ${S.H}px; overflow: hidden; background: #05070c; }
      #root { position: relative; width: 100%; height: 100%; overflow: hidden; }
    </style>
  </head>
  <body>
    <!-- cast sprite, inlined from assets/kit/cast.svg so scenes can <use href="#man"> -->
    ${castSprite}
    <div id="root" data-composition-id="main" data-start="0" data-duration="${S.total}" data-fps="30" data-width="${S.W}" data-height="${S.H}">
${hosts}
      <div id="captions" data-composition-id="captions" data-track-kind="captions" data-composition-src="compositions/captions.html"
        data-start="0" data-duration="${S.total}" data-track-index="2" data-width="${S.W}" data-height="${S.H}"></div>
${audio.join('\n')}
    </div>
    <script>
      const tl = gsap.timeline({ paused: true });
      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
`);

// ---- report
const pad = (s, n) => String(s).padEnd(n);
console.log(`${S.title}  ·  ${S.shots.length} shots  ·  ${S.totalBeats} beats @ ${S.bpm} BPM  ·  ${S.total.toFixed(1)}s`);
for (const g of groups) {
  console.log(`  ${pad(g.start.toFixed(2) + 's', 8)} ${pad(g.id, 18)} ${g.file === '_placeholder.html' ? '· placeholder' : '✓ ' + g.file}`);
}
// a "shots" scene placed in two separate groups: both instances share one timeline id, so give each place its own scene
const reused = [...new Set(groups.filter(takesShots).map(g => g.scene))].filter(n => groups.filter(g => g.scene === n).length > 1);
if (reused.length) console.log(`\n  ⚠ scenes with a "shots" variable used in more than one place: ${reused.join(', ')}`);
const missing = [...new Set(groups.filter(g => g.file === '_placeholder.html').map(g => g.scene))];
if (missing.length) console.log(`\n  scenes still to draw: ${missing.map(m => `compositions/scene-${m}.html`).join(', ')}`);
if (!audio.length) console.log('  no audio yet: run voice + score, then build again');
